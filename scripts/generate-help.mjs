import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import {dirname,resolve,join} from 'node:path';
import {fileURLToPath} from 'node:url';

// docs/*.md and manifest.json are the single authoritative help source.
// Cloudflare Workers bundle the generated TS module; Node tests can import it
// without custom asset loaders or runtime filesystem access.
const root=resolve(dirname(fileURLToPath(import.meta.url)),'../src/help');
const manifest=JSON.parse(readFileSync(join(root,'manifest.json'),'utf8'));
const topics=new Set();
const pages={};
for(const item of manifest){
 if(typeof item.topic!=='string'||!/^[a-z][a-z-]*$/.test(item.topic)
  ||typeof item.title!=='string'||!item.title.trim()
  ||typeof item.summary!=='string'||!item.summary.trim()
  ||topics.has(item.topic))throw new Error('Invalid or duplicate help topic');
 topics.add(item.topic);
 const file=join(root,item.topic+'.md');
 if(!existsSync(file))throw new Error('Missing help document: '+item.topic);
 const content=readFileSync(file,'utf8').replace(/\r\n/g,'\n');
 if(!content.startsWith('# ')||content.length<250)
  throw new Error('Help document is missing a title or meaningful content: '+item.topic);
 pages[item.topic]={title:item.title,summary:item.summary,uri:'recalloom://help/'+item.topic,content};
}
const output=[
 '/* GENERATED BY scripts/generate-help.mjs. DO NOT EDIT BY HAND. */',
 '/* Canonical sources: src/help/manifest.json and src/help/*.md */',
 'export const HELP_PAGES = '+JSON.stringify(pages,null,2)+' as const;',
 ''
].join('\n');
const target=join(root,'catalog.generated.ts');
if(process.argv.includes('--check')){
 if(!existsSync(target)||readFileSync(target,'utf8').replace(/\r\n/g,'\n')!==output){
  console.error('Recalloom help changed: run pnpm help:generate and commit the updated catalog.generated.ts');
  process.exit(1);
 }
 console.log('Verified '+Object.keys(pages).length+' help topics against compiled MCP catalog');
}else{
 writeFileSync(target,output);
 console.log('Generated '+Object.keys(pages).length+' help topics for the MCP Worker');
}