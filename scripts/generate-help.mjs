import {readFileSync,writeFileSync,existsSync,watch} from 'node:fs';
import {dirname,resolve,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {spawn} from 'node:child_process';
import {readRegistry,renderRegistry,registryDetailCatalog,REGISTRY_PATH} from './rmd-registry.mjs';

// manifest.json and *.md are the single authoritative source. The generated
// module is deterministic and can be bundled into Cloudflare Workers.
const root=resolve(dirname(fileURLToPath(import.meta.url)),'../src/help');
const target=join(root,'catalog.generated.ts');
const referenceTarget=resolve(root,'../../docs/rmd-syntax-reference.generated.md');

function compileCatalog(){
 const manifest=JSON.parse(readFileSync(join(root,'manifest.json'),'utf8'));
 if(!Array.isArray(manifest)||!manifest.length)throw new Error('Help manifest must list topics');
 const topics=new Set();
 const pages={};
 const registry=readRegistry();
 const reference=renderRegistry(registry);
 const details=registryDetailCatalog(registry);
 for(const item of manifest){
  if(typeof item.topic!=='string'||!/^[a-z][a-z-]*$/.test(item.topic)
   ||typeof item.title!=='string'||!item.title.trim()
   ||typeof item.summary!=='string'||!item.summary.trim()
   ||topics.has(item.topic))throw new Error('Invalid or duplicate help topic');
  topics.add(item.topic);
  const file=join(root,item.topic+'.md');
  if(!existsSync(file))throw new Error('Missing help document: '+item.topic);
  const content=readFileSync(file,'utf8').replace(/\r\n/g,'\n');
  if(!content.startsWith('# ')||content.length<250)
   throw new Error('Help document is missing a title or meaningful content: '+item.topic);
  pages[item.topic]={title:item.title,summary:item.summary,uri:'recalloom://help/'+item.topic,
   content:item.topic==='markdown'?content+'\n\n---\n\n'+reference:content};
 }
 const contentHash=createHash('sha256').update(JSON.stringify({manifest,pages,registry})).digest('hex');
 // schemaVersion describes the response shape. helpVersion follows actual
 // canonical content and changes automatically when a topic is edited.
 const meta={schemaVersion:1,helpVersion:'1.'+contentHash.slice(0,12),contentHash};
 return {
  topics:topics.size,reference,
  output:[
   '/* GENERATED BY scripts/generate-help.mjs. DO NOT EDIT BY HAND. */',
   '/* Canonical sources: src/help/manifest.json and src/help/*.md */',
   'export const HELP_META = '+JSON.stringify(meta,null,2)+' as const;',
   'export const HELP_PAGES = '+JSON.stringify(pages,null,2)+' as const;',
   'export const HELP_RMD_COMPONENTS = '+JSON.stringify(details.components,null,2)+' as const;',
   'export const HELP_RMD_NODES = '+JSON.stringify(details.nodes,null,2)+' as const;',
   ''
  ].join('\n')
 };
}

const args=process.argv.slice(2);
if(args.includes('--check')&&args.includes('--watch'))
 throw new Error('Cannot check and watch help simultaneously');

function generate(check=false){
 const {topics,output,reference}=compileCatalog();
 const current=existsSync(target)?readFileSync(target,'utf8').replace(/\r\n/g,'\n'):null;
 const currentRef=existsSync(referenceTarget)?readFileSync(referenceTarget,'utf8').replace(/\r\n/g,'\n'):null;
 if(check){
  if(current!==output||currentRef!==reference){
   console.error('Recalloom help changed: run pnpm help:generate and commit both generated files');
   process.exitCode=1;
  }else console.log('Verified '+topics+' help topics against compiled MCP catalog');
 }else {
  if(current!==output)writeFileSync(target,output);
  if(currentRef!==reference)writeFileSync(referenceTarget,reference);
  if(current!==output||currentRef!==reference)console.log('Generated '+topics+' topics plus the RMD component/attribute reference');
 }
}

if(args.includes('--watch')){
 generate();
 let pending;
 const update=()=>{clearTimeout(pending);pending=setTimeout(()=>{
  try{generate();}catch(error){console.error('Help generation error:',error);}
 },150);};
 const watcher=watch(root,(_event,filename)=>{
  const name=filename?.toString();
  if(name&&name!=='manifest.json'&&!name.endsWith('.md'))return;
  update();
 });
 const registryWatcher=watch(dirname(REGISTRY_PATH),(_event,filename)=>{
  if(!filename||filename.toString()==='registry.json')update();
 });
 console.log('Watching src/help/*.md and manifest.json for changes');
 const separator=args.indexOf('--');
 const command=separator>=0?args.slice(separator+1):[];
 if(command.length){
  // Local developer command, not a shell string obtained from user content.
  // Use a directly executable command (e.g. node ./node_modules/wrangler/bin/wrangler.js)
  // instead of shell:true: it keeps arguments separate on Windows and POSIX.
  const child=spawn(command[0],command.slice(1),{stdio:'inherit'});
  const close=()=>{clearTimeout(pending);watcher.close();registryWatcher.close();};
  for(const signal of ['SIGINT','SIGTERM'])process.on(signal,()=>{
   close();
   if(!child.killed)child.kill(signal);
  });
  child.on('error',error=>{console.error(error);close();process.exitCode=1;});
  child.on('exit',code=>{close();process.exitCode=code??1;});
 }
}else generate(args.includes('--check'));
