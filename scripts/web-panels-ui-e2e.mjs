import assert from 'node:assert/strict';
import {chromium} from 'playwright-core';
import {existsSync,readFileSync} from 'node:fs';
const bin=['C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe','C:/Program Files/Google/Chrome/Application/chrome.exe'].find(existsSync);
const line=readFileSync('.dev.vars','utf8').split(/\r?\n/).find(x=>/^\s*MCP_AUTH_SECRET\s*=/.test(x));
assert.ok(bin&&line,'Browser and local secret required');
const secret=line.slice(line.indexOf('=')+1).trim().replace(/^["']|["']$/g,'');
const browser=await chromium.launch({headless:true,executablePath:bin});
const origin='http://127.0.0.1:8897';
const page=await browser.newPage({viewport:{width:1440,height:900}});
try{
 await page.goto(origin+'/login');
 await page.getByPlaceholder('输入 MCP_AUTH_SECRET').fill(secret);
 await page.getByRole('button',{name:'登录',exact:true}).click();
 await page.waitForURL(origin+'/');
 await page.goto(origin+'/library');
 await page.getByRole('button',{name:'新建记录'}).click();
 const recordName='Responsive panels '+Date.now();
 await page.getByRole('textbox',{name:'名称'}).fill(recordName);
 await page.getByRole('button',{name:'创建',exact:true}).click();
 await page.waitForURL(/\/records\//);
 await page.getByRole('button',{name:'Markdown',exact:true}).click();
 await page.locator('.cm-content').fill(Array.from({length:65},(_,i)=>'## Section '+(i+1)+'\n\nParagraph for document section '+(i+1)+'.').join('\n\n'));
 await page.getByRole('button',{name:'保存',exact:true}).click();
 await page.getByRole('button',{name:'可视化',exact:true}).click();
 await page.locator('.tiptap').waitFor();
 const scrollBefore=await page.evaluate(()=>scrollY);
 await page.getByRole('button',{name:'历史',exact:true}).click();
 const dh=page.getByRole('dialog',{name:'版本历史'});
 await dh.waitFor();
 await dh.getByText(/Revision \d+/).first().waitFor({timeout:15000});
 assert.ok((await dh.boundingBox()).x>850,'desktop history opens at inline end');
 await dh.getByRole('button',{name:'关闭历史'}).click();
 await dh.waitFor({state:'hidden'});
 assert.equal(await page.evaluate(()=>scrollY),scrollBefore,'history should not jump main document');
 await page.getByRole('button',{name:'详情',exact:true}).click();
 const di=page.getByRole('dialog',{name:'记录信息'});
 await di.waitFor();
 assert.ok(await di.getByText('记录类型').count());
 assert.equal(await di.getByRole('textbox',{name:'名称'}).inputValue(),recordName);
 assert.ok(await di.getByText('Markdown 文档').count());
 await di.getByRole('button',{name:'关闭',exact:true}).click();
 await di.waitFor({state:'hidden'});
 await page.setViewportSize({width:390,height:844});
 await page.reload();
 await page.getByRole('button',{name:'详情',exact:true}).click();
 const mi=page.getByRole('dialog',{name:'记录信息'});
 await mi.waitFor();
 let bounds=await mi.boundingBox();
 assert.ok(bounds&&bounds.width>=385,'mobile detail uses bottom sheet width: '+JSON.stringify(bounds));
 await page.screenshot({path:'tmp/ux-mobile-inspector.png'});
 await mi.getByRole('button',{name:'关闭',exact:true}).click();
 await mi.waitFor({state:'hidden'});
 await page.getByRole('button',{name:'历史',exact:true}).click();
 const mh=page.getByRole('dialog',{name:'版本历史'});
 await mh.waitFor();
 bounds=await mh.boundingBox();
 assert.ok(bounds&&bounds.width>=385,'mobile history uses bottom sheet width');
 await page.screenshot({path:'tmp/ux-mobile-history.png'});
 await page.keyboard.press('Escape');
 await mh.waitFor({state:'hidden'});
 await page.screenshot({path:'tmp/ux-panels-mobile.png'});
 console.log('PASS Astryx desktop drawers, mobile bottom sheets and long-document controls');
}finally{await browser.close();}
