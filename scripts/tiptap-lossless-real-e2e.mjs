assert(edge&&secretLine);
const secret=secretLine.slice(secretLine.indexOf('=')+1).trim().replace(/^["']|["']$/g,'');
const markdown=existsSync('tmp/fidelity-target-real.md')?readFileSync('tmp/fidelity-target-real.md','utf8'):"# Agent Desktop integration\n\nInstall agent-desktop@1.0.2 for the application.\n\n## Section 1\n\nThis is regular editable prose with version information.\n\n## Section 2\n\nThis is regular editable prose with version information.\n\n## Section 3\n\nThis is regular editable prose with version information.\n\n## Section 4\n\nThis is regular editable prose with version information.\n\n## Section 5\n\nThis is regular editable prose with version information.\n\n## Section 6\n\nThis is regular editable prose with version information.\n\n## Section 7\n\nThis is regular editable prose with version information.\n\n## Section 8\n\nThis is regular editable prose with version information.\n\n## Section 9\n\nThis is regular editable prose with version information.\n\n## Section 10\n\nThis is regular editable prose with version information.\n\n## Section 11\n\nThis is regular editable prose with version information.\n\n## Section 12\n\nThis is regular editable prose with version information.\n\n## Section 13\n\nThis is regular editable prose with version information.\n\n## Section 14\n\nThis is regular editable prose with version information.\n\n## Section 15\n\nThis is regular editable prose with version information.\n\n## Section 16\n\nThis is regular editable prose with version information.\n\n## Section 17\n\nThis is regular editable prose with version information.\n\n## Section 18\n\nThis is regular editable prose with version information.\n\n**实际直接调用新版 DeskBeacon 14 个 desktop_* MCP 工具**\n\n## Conclusion\n\nRemaining document text.";
const browser=await chromium.launch({headless:true,executablePath:edge});
const origin='http://127.0.0.1:8897';
const page=await browser.newPage({viewport:{width:1250,height:820}});
page.on('pageerror',error=>console.log('PAGE_ERROR',error.message.slice(0,220)));
try{
 await page.goto(origin+'/login');
 await page.getByPlaceholder('输入 MCP_AUTH_SECRET').fill(secret);
 await page.getByRole('button',{name:'登录',exact:true}).click();
 await page.waitForURL(origin+'/');
 await page.goto(origin+'/library');
 await page.getByRole('button',{name:'新建记录'}).click();
 await page.getByRole('textbox',{name:'名称'}).fill('Lossless Tiptap real record '+Date.now());
 await page.getByRole('button',{name:'创建',exact:true}).click();
 await page.waitForURL(/\/records\//);
 await page.getByRole('button',{name:'Markdown',exact:true}).click();
 await page.locator('.cm-content').fill(markdown);
 await page.getByRole('button',{name:'保存',exact:true}).click();
 await page.getByText(/R2/).first().waitFor({timeout:20000});
 await page.getByRole('button',{name:'可视化',exact:true}).click();
 await page.locator('.tiptap').waitFor({timeout:35000});
 const blocks=await page.locator('.raw-markdown-node').count();
 const headings=await page.locator('.tiptap h2').count();
 const mode=await page.getByRole('button',{name:'Markdown',exact:true}).count();
 assert.ok(mode===1,'source mode remains optional');
 assert.ok(await page.getByRole('button',{name:'保存',exact:true}).isDisabled(),'opening visual editor does not dirty original');
 console.log('REAL_DOCUMENT',JSON.stringify({chars:markdown.length,blocks,headings,visual:true}));
 assert.ok(headings>2,'the vast majority of the long record should remain visual');
 assert.ok(blocks>=1,'unsupported content should be preserved in literal Markdown nodes');
 const target=page.locator('.tiptap h2').first();
 await target.click();
 await page.keyboard.press('End');
 await page.keyboard.type(' UPDATED');
 await page.getByRole('button',{name:'Markdown',exact:true}).click();
 await page.locator('.cm-content').waitFor();
 await page.getByRole('button',{name:'保存',exact:true}).click();
 await page.waitForTimeout(200);
 let source=await page.evaluate(async()=>{const response=await fetch('/api'+location.pathname);return (await response.json()).content;});
 assert.ok(source.includes('UPDATED'),'normal paragraphs stay editable');
 assert.ok(source.includes('**实际直接调用新版 DeskBeacon 14 个 desktop_* MCP 工具**'),'unsupported delimiters stay verbatim');
 await page.getByRole('button',{name:'可视化',exact:true}).click();
 await page.locator('.raw-markdown-node').first().waitFor();
 await page.locator('.raw-markdown-node').first().getByRole('button',{name:'编辑此段源码'}).click();
 const edit=page.getByRole('textbox',{name:'编辑原始 Markdown'}).first();
 const old=await edit.inputValue();
 await edit.fill(old+'\n\nCANCEL_THIS_RAW_EDIT');
 await page.locator('.raw-markdown-node').first().getByRole('button',{name:'取消'}).click();
 await page.locator('.raw-markdown-node').first().getByRole('button',{name:'编辑此段源码'}).click();
 assert.ok(!(await page.getByRole('textbox',{name:'编辑原始 Markdown'}).first().inputValue()).includes('CANCEL_THIS_RAW_EDIT'),'cancel restores original raw source');
 await page.getByRole('textbox',{name:'编辑原始 Markdown'}).first().fill(old+'\n\nA safe local raw edit');
 // Switching modes before clicking Apply must not lose the pending text.
 await page.getByRole('button',{name:'Markdown',exact:true}).click();
 await page.getByRole('button',{name:'保存',exact:true}).click();
 await page.waitForTimeout(200);
 source=await page.evaluate(async()=>{const response=await fetch('/api'+location.pathname);return (await response.json()).content;});
 assert.ok(source.includes('A safe local raw edit'),'raw block explicitly editable');
 console.log('PASS target real document rich text, untouched protected syntax, explicit raw editing');
}finally{await browser.close();}
