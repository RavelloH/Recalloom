export type IconName=keyof typeof glyphs;
export type IconSize='sm'|'md'|'lg';
export type IconProps=Omit<React.SVGProps<SVGSVGElement>,'name'|'width'|'height'|'stroke'|'strokeWidth'> & {name:IconName;size?:IconSize;inline?:boolean};
const sizes:Record<IconSize,number>={sm:16,md:20,lg:24};
/** The SVG itself acts as a fixed square slot; no wrapper breaks Astryx/Tiptap markup. */
export function Icon({name,size='sm',inline=false,className='',style,...rest}:IconProps){
 const Glyph=glyphs[name];
 return React.createElement(Glyph,{
   ...rest,size:inline?'1em':sizes[size],stroke:2,
   className:['rk-icon',inline?'rk-icon--inline':'rk-icon--'+size,className].filter(Boolean).join(' '),
   style,'aria-hidden':rest['aria-hidden']??true,focusable:'false'
 });
}
